import { createHash } from "node:crypto";
import { createReadStream, createWriteStream, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { pipeline } from "node:stream/promises";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import OpenCC from "opencc-js";
import { openPoems } from "../src/open-poems.js";

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const cacheRoot = join(projectRoot, ".tmp-data");
const archivePath = join(cacheRoot, "mobvoi-poetry-translations.tar.bz2");
const extractRoot = join(cacheRoot, "mobvoi-poetry-translations");
const outputPath = join(projectRoot, "src", "open-classical-translations.js");
const archiveUrl = "https://huggingface.co/datasets/ej2/seq-monkey-data/resolve/main/%E5%8F%A4%E8%AF%97%E4%BB%8A%E8%AF%91.tar.bz2";
const expectedMd5 = "42ca0782bdc0165b8e5a68186d04aa8c";
const officialDocs = "https://github.com/mobvoi/seq-monkey-data/blob/main/docs/cchs_open_corpus.md";
const targetKinds = new Set(["詞", "曲", "古文"]);
const toSimplified = OpenCC.Converter({ from: "hk", to: "cn" });
const toTraditional = OpenCC.Converter({ from: "cn", to: "hk" });

async function ensureArchive() {
  mkdirSync(cacheRoot, { recursive: true });
  if (existsSync(archivePath)) return;
  const response = await fetch(archiveUrl, {
    headers: { "User-Agent": "leafbound-classical-translation-import/1.0" },
    signal: AbortSignal.timeout(180_000)
  });
  if (!response.ok || !response.body) throw new Error(`Unable to download translation corpus: ${response.status}`);
  await pipeline(response.body, createWriteStream(archivePath));
}

async function fileMd5(path) {
  const hash = createHash("md5");
  for await (const chunk of createReadStream(path)) hash.update(chunk);
  return hash.digest("hex");
}

function ensureExtracted() {
  if (existsSync(extractRoot) && readdirSync(extractRoot).length) return;
  mkdirSync(extractRoot, { recursive: true });
  const result = spawnSync("tar", ["-xjf", archivePath, "-C", extractRoot], { encoding: "utf8" });
  if (result.status !== 0) throw new Error(`Unable to extract translation corpus: ${result.stderr || result.stdout}`);
}

function compact(value) {
  return toSimplified(String(value || ""))
    .replace(/[^\p{Script=Han}A-Za-z0-9]/gu, "")
    .trim();
}

function signature(lines) {
  return compact((lines || []).map((line) => typeof line === "string" ? line : line.text).join(""));
}

function cleanTranslation(value) {
  return toTraditional(String(value || ""))
    .replace(/\s+/gu, " ")
    .replace(/\s*([，。！？；：、])\s*/gu, "$1")
    .trim();
}

function listJsonFiles(root) {
  const files = [];
  const walk = (directory) => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.isFile() && entry.name.endsWith(".json")) files.push(path);
    }
  };
  walk(root);
  return files.sort((left, right) => left.localeCompare(right, "zh-Hans-CN"));
}

function serialize(records, byKind) {
  const source = {
    label: "Mobvoi 序列猴子古詩今譯",
    sourceUrl: officialDocs,
    license: "Apache-2.0",
    status: "機器語料 · 未經 Leafbound 人工校訂",
    archiveMd5: expectedMd5
  };
  return `// Generated by scripts/import-classical-translations.mjs. Do not edit by hand.\nconst source=Object.freeze(${JSON.stringify(source)});\nconst records=${JSON.stringify(records)};\nexport const openClassicalTranslations=Object.freeze(Object.fromEntries(records.map(([id,paragraphs])=>[id,Object.freeze({paragraphs:Object.freeze(paragraphs),source})])));\nexport const openClassicalTranslationSnapshot=Object.freeze({count:records.length,byKind:Object.freeze(${JSON.stringify(byKind)}),source});\n`;
}

await ensureArchive();
const actualMd5 = await fileMd5(archivePath);
if (actualMd5 !== expectedMd5) {
  throw new Error(`Translation archive checksum mismatch: expected ${expectedMd5}, received ${actualMd5}`);
}
ensureExtracted();

const worksBySignature = new Map(openPoems
  .filter((work) => targetKinds.has(work.kind))
  .map((work) => [signature(work.lines), work]));
const matches = new Map();

for (const file of listJsonFiles(extractRoot)) {
  const rows = JSON.parse(readFileSync(file, "utf8"));
  for (const row of Array.isArray(rows) ? rows : []) {
    const work = worksBySignature.get(signature(row.paragraph || []));
    if (!work || matches.has(work.id)) continue;
    const paragraphs = (Array.isArray(row.translate) ? row.translate : [])
      .map(cleanTranslation)
      .filter(Boolean);
    if (paragraphs.length) matches.set(work.id, { work, paragraphs });
  }
}

const records = [...matches.values()]
  .sort((left, right) => left.work.id.localeCompare(right.work.id, "en"))
  .map(({ work, paragraphs }) => [work.id, paragraphs]);
const byKind = {};
for (const { work } of matches.values()) byKind[work.kind] = (byKind[work.kind] || 0) + 1;
writeFileSync(outputPath, serialize(records, byKind), "utf8");
console.log(`Imported ${records.length} exact-match classical translations (${JSON.stringify(byKind)}).`);
