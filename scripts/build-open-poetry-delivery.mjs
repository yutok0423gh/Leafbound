import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = dirname(scriptDirectory);

function shardId(id) {
  return createHash("sha256").update(String(id)).digest("hex").slice(0, 2);
}

function compactLines(lines) {
  return (Array.isArray(lines) ? lines : []).map((line) => (
    line?.jyutping ? [String(line.text || ""), String(line.jyutping)] : String(line?.text || "")
  ));
}

function sourceMetadataFor(work) {
  return {
    source: work.source,
    sourceUrl: work.sourceUrl,
    sourceLicense: work.sourceLicense,
    sourceRevision: work.sourceRevision,
    collection: work.collection,
    jyutpingStatus: work.jyutpingStatus,
    isOpenCorpus: work.isOpenCorpus
  };
}

function serializeIndex(works) {
  const sourceIndexes = new Map();
  const sourceMetadata = [];
  const records = works.map((work) => {
    const metadata = sourceMetadataFor(work);
    const key = JSON.stringify(metadata);
    if (!sourceIndexes.has(key)) {
      sourceIndexes.set(key, sourceMetadata.length);
      sourceMetadata.push(metadata);
    }
    return [
      sourceIndexes.get(key),
      work.id,
      work.title,
      work.poet,
      work.dynasty,
      work.kind,
      work.form,
      work.themes,
      work.featuredQuote,
      work.originalSource || "",
      Array.isArray(work.lines) ? work.lines.length : 0,
      shardId(work.id)
    ];
  });

  return `// Generated by scripts/build-open-poetry-delivery.mjs. Do not edit by hand.\nconst sourceMetadata=${JSON.stringify(sourceMetadata)};\nconst records=${JSON.stringify(records)};\nexport const openPoemIndex=Object.freeze(records.map(([sourceIndex,id,title,poet,dynasty,kind,form,themes,featuredQuote,originalSource,lineCount,contentShard])=>({ ...sourceMetadata[sourceIndex],id,title,poet,dynasty,kind,form,themes,featuredQuote,...(originalSource?{originalSource}:{}),lines:String(featuredQuote||"").split(/[，。！？；]+/u).map((text)=>text.trim()).filter(Boolean).map((text)=>({text,jyutping:""})),lineCount,contentShard,contentLoaded:false,annotation:"",translation:"",appreciation:"",allusion:"" })));\n`;
}

function shardRecord(work) {
  return [
    work.id,
    compactLines(work.lines),
    String(work.annotation || ""),
    String(work.translation || ""),
    String(work.appreciation || ""),
    String(work.allusion || "")
  ];
}

export function writeOpenPoetryDelivery(works, root = projectRoot) {
  const sourceDirectory = join(root, "src");
  const dataDirectory = join(root, "data", "open-poems");
  const shardDirectory = join(dataDirectory, "shards");
  mkdirSync(shardDirectory, { recursive: true });

  const groups = new Map();
  for (const work of works) {
    const id = shardId(work.id);
    if (!groups.has(id)) groups.set(id, []);
    groups.get(id).push(shardRecord(work));
  }

  const shards = [...groups.entries()].sort(([left], [right]) => left.localeCompare(right));
  for (const [id, records] of shards) {
    const payload = { schemaVersion: 1, shard: id, records };
    writeFileSync(join(shardDirectory, `${id}.json`), `${JSON.stringify(payload)}\n`, "utf8");
  }

  const manifest = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    count: works.length,
    shardStrategy: { algorithm: "sha256-id-prefix", prefixLength: 2 },
    shards: shards.map(([id, records]) => ({ id, path: `shards/${id}.json`, count: records.length }))
  };
  writeFileSync(join(dataDirectory, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  writeFileSync(join(sourceDirectory, "open-poems-index.js"), serializeIndex(works), "utf8");
  return manifest;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { openPoems } = await import("../src/open-poems.js");
  const manifest = writeOpenPoetryDelivery(openPoems);
  console.log(JSON.stringify({ count: manifest.count, shards: manifest.shards.length }, null, 2));
}
